#!/usr/bin/env python3
"""Regenerate every catalog file from skills/*/SKILL.md.

Writes (all derived, never hand-edit them):
  skills.json                      manifest for agents, installers and the web catalog
  .claude-plugin/marketplace.json  Claude Code plugin marketplace (one plugin per skill + bundles)
  llms.txt                         llmstxt.org index for agents
  README.md                        only the block between the catalog markers and the stats line

Usage:
  python3 scripts/build-catalog.py                 # regenerate
  python3 scripts/build-catalog.py --check         # exit 1 if any generated file is stale
  python3 scripts/build-catalog.py --date 2026-10-06

Categories live in CATEGORIES below. A new skill must be added there, or the
build fails, so nothing ships uncategorised. Standard library only.
"""
